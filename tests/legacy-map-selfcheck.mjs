import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {createWorld,createPlayer,snapshot} from '../game/engine.mjs';
import {publicCatalog} from '../game/catalog.mjs';

const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const world=createWorld(),player=createPlayer(world,'旧界面空轨道验收',world.at,()=>.5),home=world.planets[player.home];
home.ships={Colony_Ship:2,Probe:1};home.resources=[1e8,1e8,1e8];
player.tech={Computer_Tech:3,Impulse_Drive:3};
const state=snapshot(world,player,home.position.slice(0,2));
const current=state.planets.find(p=>p.id===home.id),inSystem=p=>p.position[0]===home.position[0]&&p.position[1]===home.position[1],empty=state.map.filter(p=>!p.id&&inSystem(p)),npc=state.map.find(p=>p.npc&&!p.owner&&inSystem(p));
assert.ok(empty.length>1);assert.ok(npc);
const script=await build({stdin:{contents:`
  import React from 'react';
  import {createRoot} from 'react-dom/client';
  import {Game} from './client/common.jsx';
  import {Galaxy,Fleet,MoonOperations} from './client/fleets.jsx';
  const root=createRoot(document.getElementById('root'));
  window.renderLegacy=kind=>{
    Object.assign(window.fixture,{setPage:page=>window.fixture.lastPage=page,setDestination:destination=>window.fixture.destination=destination,act:async action=>{window.lastAction=action;return true;}});
    root.render(<Game.Provider value={window.fixture}>{kind==='galaxy'?<Galaxy/>:kind==='scan'?<MoonOperations scan/>:<Fleet/>}</Game.Provider>);
  };
`,resolveDir:process.cwd(),loader:'jsx'},bundle:true,write:false,format:'iife',define:{'process.env.NODE_ENV':'"development"'}});
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await page.setContent('<div id="root"></div>');
  await page.evaluate(fixture=>window.fixture=fixture,{state,planet:current,catalog:publicCatalog,now:Date.now(),busy:false});
  await page.addScriptTag({content:script.outputFiles[0].text});
  await page.evaluate(()=>renderLegacy('galaxy'));
  const first=empty[0],second=empty[1];
  assert.equal(await page.getByRole('button',{name:'侦察'+first.name,exact:true}).count(),0);
  assert.equal(await page.getByRole('button',{name:'攻击'+first.name,exact:true}).count(),0);
  await page.getByRole('button',{name:'殖民'+first.position.join(':'),exact:true}).click();
  assert.equal(await page.evaluate(()=>fixture.destination.task),'colonize');
  await page.evaluate(()=>renderLegacy('fleet'));
  const target=page.getByRole('combobox',{name:'目标星球',exact:true});
  await target.selectOption(second.position.join(':'));
  assert.equal(await page.getByRole('combobox',{name:'舰队任务'}).inputValue(),'colonize');
  const values=await target.locator('option').evaluateAll(options=>options.map(o=>o.value));
  assert.equal(new Set(values).size,values.length,'empty orbits must have distinct coordinate option keys');
  await target.selectOption(npc.id);
  assert.equal(await page.getByRole('combobox',{name:'舰队任务'}).inputValue(),'attack','ownerless NPCs are occupied');
  await target.selectOption(second.position.join(':'));
  await page.locator('.launch-button').click();
  const action=await page.evaluate(()=>lastAction);
  assert.equal(action.target,'');assert.equal(action.task,'colonize');assert.deepEqual(action.position,second.position);
  await page.getByRole('button',{name:'星际导弹',exact:true}).click();
  const missileTargets=await page.getByRole('combobox',{name:'导弹目标星球'}).locator('option').evaluateAll(options=>options.map(o=>o.value));
  assert.ok(missileTargets.includes(npc.id));assert.ok(!missileTargets.includes(second.position.join(':')));
  await page.evaluate(()=>renderLegacy('scan'));
  const scanTargets=await page.getByRole('combobox',{name:'扫描目标'}).locator('option').evaluateAll(options=>options.map(o=>o.value));
  assert.ok(scanTargets.includes(npc.id));assert.ok(!scanTargets.includes(second.position.join(':')));
  assert.deepEqual(errors,[]);
  console.log('Legacy nullable-orbit targets: colony routing, NPC attack, unique select values, scan/missile filters passed.');
}finally{await browser.close();}
