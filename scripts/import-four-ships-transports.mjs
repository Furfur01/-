import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {transform} from 'esbuild';
import {writeBuildFile} from './write-build-file.mjs';

// Extract only the two transport factories and their geometry helpers. The HTML,
// embedded Three.js runtime and demo UI are never executed by the importer.
const root=path.resolve(import.meta.dirname,'..');
const reference=path.join(root,'models/reference/four-ships/Four_Ships_ThreeJS_Offline.html');
const html=fs.readFileSync(process.argv[2]?path.resolve(process.argv[2]):reference,'utf8');
const section=(start,end)=>{
  const a=html.indexOf('function '+start+'('),b=html.indexOf('function '+end+'(',a);
  assert(a>=0&&b>a,`Missing source factory section: ${start}–${end}`);
  return html.slice(a,b);
};
let source=section('sg','rg')+section('jh','pg');
assert(source.includes('T02_Small_Transport')&&source.includes('T03_Large_Transport'));
assert(!source.includes('document.')&&!source.includes('window.'));
for(const [from,to]of Object.entries({sg:'createTransportTools',jh:'sidePlate',wl:'mirrorOutline',og:'cargoDeck',ag:'bowFrame',lg:'cargoGirder',cg:'cargoBulkhead',hg:'crewBridge',ug:'mainEngine',dg:'smallTransport',fg:'largeTransport'})){
  source=source.replace(new RegExp('\\b'+from+'\\b','g'),to);
}
source+='\nexport function createTransportSource(THREE,id){\n'+
  "  if(!['Cargo_Ship','Large_Cargo_Ship'].includes(id))throw Error('Unknown transport: '+id);\n"+
  "  return (id==='Cargo_Ship'?smallTransport:largeTransport)(THREE,createTransportTools(THREE));\n}\n";
const formatted=await transform(source,{format:'esm',target:'es2022',minify:false});
if(process.argv[2]){
  fs.mkdirSync(path.dirname(reference),{recursive:true});
  writeBuildFile(reference,html);
}
writeBuildFile(path.join(root,'opendesign/mockups/galactic-command/cargo-reference-geometry.js'),
  '// Generated by scripts/import-four-ships-transports.mjs from the retained user HTML.\n'+
  '// Original T02 / T03 geometry and materials; edit the adapter for game integration.\n'+formatted.code);
console.log('Imported T02 and T03 transport geometry; missile and colony models excluded.');
