import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

// Import only the embedded model, never execute the supplied HTML.
// With no argument, regenerate the browser module from the retained GLB.
const root=path.resolve(import.meta.dirname,'..');
const reference=path.join(root,'models/reference/sr07-salvage/SR07-original.glb');
let bytes;
if(process.argv[2]){
  const html=fs.readFileSync(path.resolve(process.argv[2]),'utf8');
  const encoded=html.match(/<script\b[^>]*\bid="model-data"[^>]*>([\s\S]*?)<\/script>/)?.[1];
  assert(encoded,'The SR-07 HTML must contain its embedded model-data');
  bytes=Buffer.from(encoded.trim(),'base64');
}else bytes=fs.readFileSync(reference);
assert.equal(bytes.toString('ascii',0,4),'glTF');
assert.equal(bytes.readUInt32LE(8),bytes.length);
const doc=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)));
assert.equal(doc.extras.triangles,25948);
assert.equal(doc.nodes.length,12);
if(process.argv[2]){
  fs.mkdirSync(path.dirname(reference),{recursive:true});
  fs.writeFileSync(reference,bytes);
}
const output=path.join(root,'opendesign/mockups/galactic-command/recycler-sr07-data.js');
fs.writeFileSync(output,'// Generated by scripts/import-sr07-salvage.mjs; original geometry, no palette edits.\nexport const sr07GLB='+JSON.stringify(bytes.toString('base64'))+';\n');
console.log('SR-07 imported: '+doc.extras.triangles+' triangles / '+doc.extras.meshPrimitives+' primitives');
