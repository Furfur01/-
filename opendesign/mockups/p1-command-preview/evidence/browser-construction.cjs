async (page) => {
  page.setDefaultTimeout(5000);
  const checks=[];
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')));
  const ok=(value,name)=>{if(!value)throw new Error(name);checks.push(name);};
  await page.getByRole('button',{name:'重置示例',exact:true}).click();
  await page.getByLabel('演示速度').selectOption('0');
  const initial=await state();
  await page.getByRole('button',{name:'开始升级',exact:true}).click();
  let s=await state();ok(!!s.planets[0].build,'Construction starts and UI displays active build');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/construction-active.png'});
  await page.getByRole('button',{name:'取消施工',exact:true}).click();
  s=await state();ok(!s.planets[0].build,'Cancel removes current construction');
  ok(JSON.stringify(s.planets.map(p=>p.resources))===JSON.stringify(initial.planets.map(p=>p.resources)),'Cancel returns unchanged resource balance');
  await page.getByLabel('当前示例殖民地').selectOption({label:'霜庭 · 1:32:10'});
  ok(await page.getByRole('button',{name:'资源不足',exact:true}).isDisabled(),'Frost resources block direct construction');
  await page.getByRole('button',{name:'工业',exact:true}).click();
  await page.getByRole('button',{name:/纳米工厂/}).click();
  ok(await page.getByRole('button',{name:'前置条件未满足',exact:true}).isDisabled(),'Insufficient prerequisites block advanced facility');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/construction-blocked.png'});
  await page.getByLabel('当前示例殖民地').selectOption({label:'曙光 · 1:16:7'});
  await page.getByRole('button',{name:/管理建设计划/}).click();
  await page.getByRole('button',{name:'启用计划',exact:true}).click();
  ok(!(await state()).planets[0].paused,'Enable plan changes its state');
  await page.getByRole('button',{name:'暂停后续',exact:true}).click();
  ok((await state()).planets[0].paused,'Pause future construction changes its state');
  const original=(await state()).planets[0].plan.map(x=>x.id);
  await page.getByRole('button',{name:'下移第1项',exact:true}).click();
  ok((await state()).planets[0].plan[1].id===original[0],'Move plan item down updates sequence');
  await page.getByLabel('计划设施').selectOption({label:'太阳能电站'});
  await page.getByLabel('计划目标等级').fill('18');
  await page.getByRole('button',{name:'加入计划',exact:true}).click();
  ok((await state()).planets[0].plan.some(x=>x.id==='Solar_Plant'&&x.level===18),'Add plan target succeeds');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/plan-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/plan-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'关闭面板',exact:true}).click();
  await page.setViewportSize({width:1280,height:720});
  await page.getByRole('button',{name:'帝国王庭',exact:true}).click();
  await page.getByLabel('选择霜庭',{exact:true}).check();
  await page.getByLabel('选择远望',{exact:true}).check();
  await page.getByLabel('发展计划类型').selectOption('incremental');
  await page.getByRole('button',{name:'预览批量计划',exact:true}).click();
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/template-preview.png'});
  const before=await state();
  await page.getByRole('button',{name:'确认应用到 2 颗星球',exact:true}).click();
  s=await state();
  ok(s.planets[2].plan.length>before.planets[2].plan.length&&s.planets[3].plan.length>before.planets[3].plan.length,'Batch template adds targets to both selected colonies');
  ok(JSON.stringify(s.planets.map(p=>p.resources))===JSON.stringify(before.planets.map(p=>p.resources)),'Template preview/apply does not precharge resources');
  await page.getByLabel('搜索殖民地').fill('远望');
  ok(await page.locator('.colony-table tbody tr').count()===1,'Colony search filters to one result');
  await page.locator('.colony-name').click();
  ok((await state()).selected===(await state()).planets[3].id,'Colony row navigates to selected construction');
  return checks;
}
