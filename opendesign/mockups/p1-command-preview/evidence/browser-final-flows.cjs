async (page) => {
  page.setDefaultTimeout(5000);
  const checks=[];
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')));
  const ok=(value,name)=>{if(!value)throw new Error(name);checks.push(name);};
  await page.setViewportSize({width:1280,height:720});
  await page.getByRole('button',{name:'重置示例',exact:true}).click();
  await page.getByLabel('演示速度').selectOption('0');
  await page.getByRole('button',{name:'殖民地建设',exact:true}).click();
  await page.locator('.action-body').hover();await page.mouse.wheel(0,700);await page.waitForTimeout(150);
  ok(await page.locator('.action-body').evaluate(e=>e.scrollTop>0),'1280 construction prerequisites scroll into view');
  await page.locator('.facility-list').hover();await page.mouse.wheel(0,700);await page.waitForTimeout(150);
  ok(await page.locator('.facility-list').evaluate(e=>e.scrollTop>0),'1280 facility list scrolls to lower items');
  await page.getByRole('button',{name:'固定建设区',exact:true}).click();
  ok(await page.locator('.slot-grid button').count()===14,'Fixed construction area contains all 14 indexed facilities');
  await page.locator('.slot-grid button[title="研究实验室"]').click();
  ok(await page.getByRole('heading',{name:'研究实验室',exact:true}).isVisible(),'Fixed-area facility switches selected detail');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/construction-map.png'});
  await page.getByRole('button',{name:'帝国王庭',exact:true}).click();
  await page.locator('.colony-table-wrap').hover();await page.mouse.wheel(0,800);await page.waitForTimeout(150);
  ok(await page.locator('.colony-table-wrap').evaluate(e=>e.scrollTop>0),'1280 colony table scroll reaches last colony');
  await page.locator('.template-panel').hover();await page.mouse.wheel(0,800);await page.waitForTimeout(150);
  ok(await page.locator('.template-panel').evaluate(e=>e.scrollTop>0),'1280 development template controls are reachable by scroll');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.colony-table-wrap').hover();await page.mouse.wheel(600,0);await page.waitForTimeout(150);
  ok(await page.locator('.colony-table-wrap').evaluate(e=>e.scrollLeft>0),'390 colony table allows internal horizontal scroll');
  await page.getByRole('button',{name:'建设计划',exact:true}).first().click();
  await page.locator('dialog').hover();await page.mouse.wheel(0,700);await page.waitForTimeout(150);
  ok(await page.locator('dialog').evaluate(e=>e.scrollTop>0||e.scrollHeight<=e.clientHeight),'390 plan dialog scrolls to bottom content');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/plan-mobile-scrolled.png'});
  await page.getByRole('button',{name:'关闭面板',exact:true}).click();
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'舰队行动',exact:true}).click();
  await page.getByRole('button',{name:/^霜庭/}).click();
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.getByLabel('重型运输舰派遣数量').fill('1');
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.getByLabel('装载金属').fill('1000');
  const before=await state();
  await page.getByRole('button',{name:'确认派遣',exact:true}).click();
  let s=await state(),mission=s.missions.find(m=>!before.missions.some(x=>x.id===m.id));
  await page.getByLabel('演示速度').selectOption('60');
  await page.waitForFunction(id=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')).missions.find(m=>m.id===id).phase==='return',mission.id,{timeout:15000});
  s=await state();ok(s.planets[2].resources[0]>=before.planets[2].resources[0]+1000,'Transport arrival unloads cargo to target colony');
  ok(s.missions.find(m=>m.id===mission.id).cargo.every(x=>x===0),'Transport cargo is empty after delivery');
  await page.waitForFunction(id=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')).missions.find(m=>m.id===id).phase==='completed',mission.id,{timeout:15000});
  await page.getByLabel('演示速度').selectOption('0');
  ok((await state()).planets[0].ships.Large_Cargo_Ship===before.planets[0].ships.Large_Cargo_Ship,'Completed transport restores port ships');
  const stopped=await state();await page.waitForTimeout(1200);
  ok(JSON.stringify((await state()).planets)===JSON.stringify(stopped.planets),'Pause keeps simulation state unchanged');
  return checks;
}
