async (page) => {
  page.setDefaultTimeout(5000);
  const checks=[];
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')));
  const ok=(value,name)=>{if(!value)throw new Error(name);checks.push(name);};
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'重置示例',exact:true}).click();
  await page.getByLabel('演示速度').selectOption('0');
  await page.getByRole('button',{name:'行星防务',exact:true}).click();
  await page.getByLabel('防御建造数量').fill('2');
  await page.getByRole('button',{name:'加入生产队列',exact:true}).click();
  ok((await state()).planets[0].defenseQueue[0].remaining===2,'Production queues two plasma cannons');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/defense-production.png'});
  await page.getByLabel('演示速度').selectOption('60');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')).planets[0].defense.Plasma_Cannon===2,null,{timeout:25000});
  await page.getByLabel('演示速度').selectOption('0');
  ok((await state()).planets[0].defenseQueue.length===0,'60x completes batch and increments deployed count to two');
  await page.getByRole('button',{name:'防护盾',exact:true}).click();
  await page.getByRole('button',{name:/小型防护盾/}).click();
  ok(await page.getByRole('button',{name:'每种防护盾限一座',exact:true}).isDisabled(),'Already-deployed small shield cannot be duplicated');
  await page.getByRole('button',{name:'舰队行动',exact:true}).click();
  await page.getByRole('button',{name:/^霜庭/}).click();
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.getByLabel('重型运输舰派遣数量').fill('2');
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.getByLabel('装载金属').fill('12000');
  await page.getByLabel('装载晶体').fill('4000');
  await page.getByRole('button',{name:'75%',exact:true}).click();
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/fleet-confirm.png'});
  const before=await state();
  await page.getByRole('button',{name:'确认派遣',exact:true}).click();
  let s=await state(),mission=s.missions.find(m=>!before.missions.some(x=>x.id===m.id));
  ok(!!mission&&mission.cargo[0]===12000&&mission.ships.Large_Cargo_Ship===2,'Three-step transport dispatch creates configured mission');
  ok(s.planets[0].ships.Large_Cargo_Ship===before.planets[0].ships.Large_Cargo_Ship-2,'Dispatch removes assigned ships from port');
  await page.locator('.mission-card').filter({hasText:'曙光'}).filter({hasText:'霜庭'}).first().click();
  await page.getByRole('button',{name:'召回舰队',exact:true}).click();
  ok((await state()).missions.find(m=>m.id===mission.id).phase==='return','Recall changes transport to returning phase');
  await page.getByRole('button',{name:'返航',exact:true}).click();
  ok(await page.locator('.mission-card').count()>=1,'Return filter shows recalled mission');
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/fleet-recalled.png'});
  await page.getByLabel('演示速度').selectOption('60');
  await page.waitForFunction(id=>JSON.parse(localStorage.getItem('galaxy-empire-p1-independent-v1')).missions.find(m=>m.id===id).phase==='completed',mission.id,{timeout:25000});
  await page.getByLabel('演示速度').selectOption('0');
  ok((await state()).planets[0].ships.Large_Cargo_Ship===before.planets[0].ships.Large_Cargo_Ship,'Recalled fleet returns ships to port');
  await page.getByRole('button',{name:'来袭',exact:true}).click();
  ok(await page.locator('.mission-card').count()===1&&await page.getByRole('heading',{name:'来袭舰队预警',exact:true}).isVisible(),'Incoming filter shows threat details');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'opendesign/mockups/p1-command-preview/evidence/fleet-incoming-mobile.png',fullPage:true});
  return checks;
}
